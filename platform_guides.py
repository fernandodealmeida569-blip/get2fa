def make(lang):
    t = LANGT[lang]
    out = {}
    for key, p in PLAT.items():
        d = p.get(lang)
        if not d:
            continue
        f = dict(name=p["name"], id=p["pid"], home=t["home"], nw=t["nw"], fk=t["fk"], lp=t["lp"])
        steps = "".join(f"<li>{s}</li>" for s in d["steps"])
        probs = "".join(f"<li>{s.format(**f)}</li>" for s in t["probs"])
        body = (f"\n<h2>{t['hSteps']}</h2>\n<ol>{steps}</ol>\n<p>{d['note']}</p>\n"
                f"<h2>{t['hKeep']}</h2>\n<p>{t['pKeep'].format(**f)}</p>\n"
                f"<h2>{t['hMulti']}</h2>\n<p>{t['pMulti']}</p>\n"
                f"<h2>{t['hProb']}</h2>\n<ul>{probs}</ul>\n")
        out[key] = {"slug": t["slug"].format(**f), "title": t["title"].format(**f), "desc": t["desc"].format(**f),
                    "h1": t["h1"].format(**f), "lead": t["lead"].format(**f), "body": body}
    return out
